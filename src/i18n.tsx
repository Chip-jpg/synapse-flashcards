export type MessageKey = keyof typeof en;
type Params = Record<string, string | number>;
const Context = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: "en",
  setLang: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = localStorage.getItem("synapse.lang");
    if (saved === "it" || saved === "en") return saved;
    return navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
  });
  useEffect(() => {
    localStorage.setItem("synapse.lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  return <Context.Provider value={{ lang, setLang }}>{children}</Context.Provider>;
}
export function useLang() {
  return useContext(Context);
}

export function translate(lang: Lang, key: MessageKey, params: Params = {}) {
  return (lang === "it" ? it : en)[key].replace(/\{(\w+)\}/g, (match, name: string) =>
    String(params[name] ?? match)
  );
}

export function useT() {
  const { lang } = useLang();
  const t = (key: MessageKey, params: Params = {}) => translate(lang, key, params);
  const plural = (count: number, one: MessageKey, other: MessageKey, params: Params = {}) =>
    t(count === 1 ? one : other, { ...params, count });
  return { t, plural };
}
